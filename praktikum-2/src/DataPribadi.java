// Mmenunjukkan lokasi file dengan nama DataPribadi
public class DataPribadi {

    // Method utama yang pertama kali jalan
    public static void main(String[] args) {

        // Membuat variabel umur bertipe integer
        int umur = 19;

        // Membuat variabel tinggiBadan bertipe double
        double tinggiBadan = 175.5;

        // Membuat variabel inisial bertipe char
        char inisial = 'S';

        // Membuat variabel mahasiswaAktif bertipe boolean
        boolean mahasiswaAktif = true;

        // Menampilkan umur + satuan tahun
        System.out.println("Umur: " + umur + " tahun");

        // Menampilkan tinggi badan + satuan cm
        System.out.println("Tinggi badan: " + tinggiBadan + " cm");

        // Menampilkan inisial
        System.out.println("Inisial: " + inisial);

        // Menampilkan status mahasiswa
        System.out.println("Mahasiswa aktif: " + mahasiswaAktif);
    }
}
